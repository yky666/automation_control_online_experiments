%任务3-2：由零极点增益模型转为多项式模型，再进行部分分式展开

%清理工作区和命令行窗口
clc;

% 零极点增益参数
z = [-1+1j, -1-1j]';        % 零点：-1+j，-1-j
p = [0, 0, -5, 1j, -1j]';   % 极点：二重极点0，极点-5，极点j和-j
k = 8;                      % 系统增益

% [num,den]=zp2tf(z,p,k) 将零极点增益模型转为分子、分母多项式系数
[num,den] = zp2tf(z,p,k)

% [r,p,k]=residue(num,den) 将有理分式展开为部分分式形式
[r,p,k] = residue(num,den)

% 同时输出传递函数模型，便于检查展开前的系统形式
Gs = tf(num,den)
