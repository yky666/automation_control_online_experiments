%任务2-2：建立控制系统的零极点增益模型
% G(s)=1/[s(s-1)(s^3+s^2+1)]

%清理工作区和命令行窗口
clc;

%% 写法1：定义s算子，直接写数学表达式
s = tf('s');
Gs2 = 1/(s*(s - 1)*(s^3 + s^2 + 1))

%% 写法2：零极点增益模型
% 分子为常数1，因此没有有限零点
z2 = [];

% 极点包括 s=0、s=1，以及 s^3+s^2+1=0 的三个根
p_extra = roots([1 1 0 1]);
p2 = [0; 1; p_extra];

% 增益
k2 = 1;

% 调用 sys=zpk(z,p,k) 建立零极点增益模型
Gzpk2 = zpk(z2,p2,k2)

% 转为传递函数形式，便于检查与原表达式是否一致
Gtf2 = tf(Gzpk2)
