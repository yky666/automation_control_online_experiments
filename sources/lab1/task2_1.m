%任务2-1：建立控制系统的零极点增益模型
% G(s)=8(s+1-j)(s+1+j)/[s^2(s+5)(s+6)(s^2-1)]

%清理工作区和命令行窗口
clc;

%% 写法1：定义s算子，直接写数学表达式
s = tf('s');
Gs1 = 8*(s + 1 - 1j)*(s + 1 + 1j)/(s^2*(s + 5)*(s + 6)*(s^2 - 1))

%% 写法2：零极点增益模型
% 零点：-1+j，-1-j
z1 = [-1+1j; -1-1j];

% 极点：二重极点0，极点-5、-6、1、-1
p1 = [0; 0; -5; -6; 1; -1];

% 增益
k1 = 8;

% 调用 sys=zpk(z,p,k) 建立零极点增益模型
Gzpk1 = zpk(z1,p1,k1)

% 转为传递函数形式，便于和直接写出的Gs1对比
Gtf1 = tf(Gzpk1)
